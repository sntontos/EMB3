"""Downloads the datasets, stores them in canonical form, writes the statistics table and
creates the cross-validation splits. Run it in the main environment:

    scripts/prepare_data.sh

Existing splits are never overwritten, only checked, so that results stay comparable.
Pass --regenerate-splits to replace them on purpose.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path
from typing import Any, Dict, List

import numpy as np

from emb3.config import load_config, project_path
from emb3.graphs import GraphDataset, processed_path
from emb3.splits import Splits, load_splits, make_splits, save_splits, splits_path
from emb3.tudataset import download, parse


def statistics(dataset: GraphDataset) -> Dict[str, Any]:
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import connected_components

    total = dataset.total_nodes
    edges = dataset.edges
    adjacency = coo_matrix((np.ones(len(edges), dtype=np.int8), (edges[:, 0], edges[:, 1])), shape=(total, total))
    _, component = connected_components(adjacency, directed=False)
    # One representative node per component tells which graph the component belongs to.
    representatives = np.unique(component, return_index=True)[1]
    components_per_graph = np.bincount(dataset.graph_of_node()[representatives], minlength=len(dataset))
    degrees = dataset.degrees()
    class_sizes = np.bincount(dataset.y)
    if dataset.label_kind == "native":
        labels = "{} (from the dataset)".format(dataset.num_node_labels)
    else:
        labels = "{} (node degree)".format(len(np.unique(dataset.node_labels)))
    return {
        "dataset": dataset.name,
        "graphs": len(dataset),
        "classes": dataset.num_classes,
        "smallest_class": int(class_sizes.min()),
        "largest_class": int(class_sizes.max()),
        "avg_nodes": round(float(dataset.num_nodes.mean()), 2),
        "max_nodes": int(dataset.num_nodes.max()),
        "avg_edges": round(float(dataset.num_edges.mean()), 2),
        "max_edges": int(dataset.num_edges.max()),
        "max_degree": int(degrees.max()),
        "distinct_node_labels": labels,
        "disconnected_graphs": int(np.sum(components_per_graph > 1)),
        "isolated_nodes": int(np.sum(degrees == 0)),
    }


def _table(header: List[str], rows: List[List[Any]]) -> List[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return lines


def write_statistics(out_dir: Path, stats: List[Dict[str, Any]], cleaning: Dict[str, Dict[str, Any]], digests: Dict[str, str]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "statistics.csv", "w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(stats[0]))
        writer.writeheader()
        writer.writerows(stats)

    lines = ["# Dataset statistics", "", "Generated by `scripts/prepare_data.sh`. Do not edit by hand.", ""]
    lines += _table(
        ["Dataset", "Graphs", "Classes", "Class sizes", "Avg nodes", "Avg edges", "Max nodes", "Max degree",
         "Node labels", "Disconnected graphs", "Isolated nodes"],
        [[s["dataset"], s["graphs"], s["classes"], "{}–{}".format(s["smallest_class"], s["largest_class"]),
          "{:.2f}".format(s["avg_nodes"]), "{:.2f}".format(s["avg_edges"]), s["max_nodes"], s["max_degree"],
          s["distinct_node_labels"], s["disconnected_graphs"], s["isolated_nodes"]] for s in stats],
    )
    lines += [
        "",
        "Edges are undirected and counted once. Graphs are stored as simple graphs: self-loops and",
        "repeated entries in the source files are dropped.",
        "",
        "## Source files and clean-up",
        "",
    ]
    lines += _table(
        ["Dataset", "Entries in A.txt", "Self-loops removed", "Duplicate entries removed",
         "Edges listed in one direction only", "Undirected edges kept", "SHA-256 of the archive"],
        [[name, c["entries_in_file"], c["self_loops_removed"], c["duplicate_entries_removed"],
          c["edges_listed_in_one_direction_only"], c["undirected_edges_kept"], "`{}`".format(digests[name])]
         for name, c in cleaning.items()],
    )
    (out_dir / "statistics.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def ensure_splits(dataset: GraphDataset, config: Dict[str, Any], regenerate: bool) -> str:
    import sklearn

    spec = config["cross_validation"][config["datasets"][dataset.name]["size"]]
    seeds = config["seeds"]["splits"][: spec["repeats"]]
    fraction = config["cross_validation"]["validation_fraction"]
    path = splits_path(dataset.name, config)
    if path.exists() and not regenerate:
        splits = load_splits(dataset.name, config)
        splits.check(dataset.y)
        stored = [entry["seed"] for entry in splits.record["repeats"]]
        if splits.n_folds != spec["folds"] or stored != seeds or splits.record["validation_fraction"] != fraction:
            raise RuntimeError("{} does not match the configuration. Use --regenerate-splits to replace it.".format(path))
        return "kept"
    record = {
        "dataset": dataset.name,
        "n_graphs": len(dataset),
        "n_folds": spec["folds"],
        "validation_fraction": fraction,
        "generated_with": {"scikit-learn": sklearn.__version__, "numpy": np.__version__},
        "repeats": make_splits(dataset.y, spec["folds"], seeds, fraction),
    }
    Splits(record).check(dataset.y)
    save_splits(path, record)
    return "created"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", default=None, help="configuration file (default: configs/default.yaml)")
    parser.add_argument("--regenerate-splits", action="store_true", help="replace existing split files")
    args = parser.parse_args()

    config = load_config(args.config)
    raw_dir = project_path(config, "data") / "raw"
    stats, cleaning, digests = [], {}, {}
    for name, spec in config["datasets"].items():
        archive, digest = download(name, raw_dir, config["tudataset_url"], spec.get("sha256"))
        dataset, cleaned = parse(archive, name, spec["node_labels"])
        dataset.save(processed_path(name, config))
        stats.append(statistics(dataset))
        cleaning[name], digests[name] = cleaned, digest
        outcome = ensure_splits(dataset, config, args.regenerate_splits)
        print("{}: {} graphs, {} nodes, {} edges; splits {}; sha256 {}".format(
            name, len(dataset), dataset.total_nodes, len(dataset.edges), outcome, digest), file=sys.stderr)
    write_statistics(project_path(config, "results") / "datasets", stats, cleaning, digests)


if __name__ == "__main__":
    main()
